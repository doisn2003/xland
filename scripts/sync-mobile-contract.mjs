import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { createHash } from "node:crypto";

// Explicit developer command. The web build never needs a sibling checkout.
const root = resolve(
  process.argv[2] ?? "../../xland-mobile/lib/domain/entities",
);
const names = [
  "common",
  "property",
  "social",
  "consultant",
  "event",
  "booking",
  "account",
  "finance",
];
const sources = await Promise.all(
  names.map((name) => readFile(resolve(root, name + ".dart"), "utf8")),
);
const enums = {},
  schemas = {};
const special = {
  below100: "below_100",
  from100To200: "from_100_to_200",
  above200: "above_200",
};
const wire = (value) =>
  special[value] ?? value.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase());
for (const source of sources) {
  for (const [, name, values] of source.matchAll(
    /enum (\w+) \{([\s\S]*?)\}/g,
  )) {
    enums[name] = values
      .split(",")
      .map((s) => s.trim())
      .filter((s) => /^[a-z]\w*$/.test(s))
      .map(wire);
  }
  for (const [, name, body] of source.matchAll(
    /final class (\w+)(?:<[^>]+>)?[^\{]*\{([\s\S]*?)\n\}/g,
  )) {
    if (["Page", "PropertySearchResult"].includes(name)) continue;
    schemas[name] = Object.fromEntries(
      [...body.matchAll(/final ([\w<>?]+) (\w+);/g)].map(([, type, key]) => [
        key,
        type,
      ]),
    );
  }
}
function ts(type) {
  if (type.endsWith("?")) return ts(type.slice(0, -1)) + " | null";
  if (type.startsWith("List<")) return "(" + ts(type.slice(5, -1)) + ")[]";
  return (
    {
      Uint8List: "number[]",
      String: "string",
      Uri: "string",
      DateTime: "string",
      Vnd: "string",
      DecimalValue: "string",
      int: "number",
      double: "number",
      bool: "boolean",
    }[type] ?? type
  );
}
const digest = createHash("sha256")
  .update(sources.map((s) => s.replace(/\r\n/g, "\n")).join("\n"))
  .digest("hex");
let out =
  "// Generated by scripts/sync-mobile-contract.mjs from mobile domain entities.\n";
out += "// SHA256 (LF normalized): " + digest + "\n";
for (const [name, values] of Object.entries(enums))
  out += `export type ${name} = ${values.map((v) => JSON.stringify(v)).join(" | ")};\n`;
for (const [name, fields] of Object.entries(schemas)) {
  out += `export interface ${name} {\n`;
  for (const [key, type] of Object.entries(fields))
    out += `  ${key}: ${ts(type)};\n`;
  out += "}\n";
}
out +=
  "\nexport interface WireTypes {\n" +
  Object.keys(schemas)
    .map((n) => `  ${n}: ${n};`)
    .join("\n") +
  "\n}\n";
out +=
  "export const wireEnums: Record<string, readonly string[]> = " +
  JSON.stringify(enums, null, 2) +
  ";\n";
out +=
  "export const wireSchemas: Record<string, Record<string, string>> = " +
  JSON.stringify(schemas, null, 2) +
  ";\n";
await mkdir("src/features/user", { recursive: true });
await writeFile("src/features/user/contract.ts", out);
console.log(
  "Generated " +
    Object.keys(schemas).length +
    " DTOs and " +
    Object.keys(enums).length +
    " enums from mobile.",
);
